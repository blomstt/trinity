using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Trinity.Generators;

/// <summary>
/// Finds every class deriving from Trinity.Scenes.Script in a game and writes code that registers it at
/// start-up: how to create one, and a setter for each public field the editor can set. Scenes then create
/// scripts by name without reflection, which NativeAOT needs.
/// </summary>
[Generator]
public sealed class ScriptGenerator : IIncrementalGenerator
{
    static readonly Dictionary<string, string> Readers = new()
    {
        ["float"] = "v.GetSingle()",
        ["double"] = "v.GetDouble()",
        ["int"] = "v.GetInt32()",
        ["bool"] = "v.GetBoolean()",
        ["string"] = "v.GetString() ?? \"\"",
        ["System.Numerics.Vector3"] = "global::Trinity.Scenes.Scripts.ReadVector3(v)",
    };

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var scripts = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList: not null },
                static (ctx, _) => Describe((INamedTypeSymbol?)ctx.SemanticModel.GetDeclaredSymbol(ctx.Node))
            )
            .Where(static s => s != null)
            .Collect();
        context.RegisterSourceOutput(scripts, static (output, found) => Write(output, found!));
    }

    sealed record ScriptInfo(string Name, string FullName, ImmutableArray<(string Name, string Read)> Fields);

    static ScriptInfo? Describe(INamedTypeSymbol? type)
    {
        if (type == null || type.IsAbstract || type.IsGenericType || type.DeclaredAccessibility == Accessibility.Private)
            return null;
        if (!type.InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaredAccessibility != Accessibility.Private))
            return null;
        var isScript = false;
        for (var b = type.BaseType; b != null; b = b.BaseType)
            if (b.ToDisplayString() == "Trinity.Scenes.Script")
                isScript = true;
        if (!isScript)
            return null;

        var fields = ImmutableArray.CreateBuilder<(string, string)>();
        for (var t = type; t != null && t.ToDisplayString() != "Trinity.Scenes.Script"; t = t.BaseType)
            foreach (var member in t.GetMembers())
            {
                if (member.DeclaredAccessibility != Accessibility.Public || member.IsStatic)
                    continue;
                var memberType = member switch
                {
                    IFieldSymbol { IsReadOnly: false, IsConst: false } f => f.Type,
                    IPropertySymbol { SetMethod: { DeclaredAccessibility: Accessibility.Public, IsInitOnly: false }, IsIndexer: false } p => p.Type,
                    _ => null,
                };
                if (memberType != null && Readers.TryGetValue(memberType.ToDisplayString(), out var read))
                    fields.Add((member.Name, read));
            }
        return new ScriptInfo(type.Name, type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), fields.ToImmutable());
    }

    static void Write(SourceProductionContext output, ImmutableArray<ScriptInfo> scripts)
    {
        if (scripts.IsEmpty)
            return;
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/> by Trinity.Generators: the game's scripts, registered without reflection");
        code.AppendLine("namespace Trinity.Generated;");
        code.AppendLine();
        code.AppendLine("static class TrinityScripts");
        code.AppendLine("{");
        code.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        code.AppendLine("    internal static void Register()");
        code.AppendLine("    {");
        foreach (var s in scripts.GroupBy(s => s.FullName).Select(g => g.First()).OrderBy(s => s.Name))
        {
            code.Append($"        global::Trinity.Scenes.Scripts.Register(\"{s.Name}\", static () => new {s.FullName}()");
            foreach (var (name, read) in s.Fields)
                code.Append($",\n            (\"{name}\", static (s, v) => (({s.FullName})s).{name} = {read})");
            code.AppendLine(");");
        }
        code.AppendLine("    }");
        code.AppendLine("}");
        output.AddSource("TrinityScripts.g.cs", code.ToString());
    }
}
